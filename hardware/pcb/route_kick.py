"""Route the tx-kick board and write routes_kick.py for build_kick.py."""
import sys, pprint
import route_kick_lib as rk

order = sys.argv[1].split(",") if len(sys.argv) > 1 else rk.ORDER
tracks, vias, failed = rk.route(order)
with open("routes_kick.py", "w") as f:
    f.write("# generated by route_kick.py\nROUTES = " + pprint.pformat(tracks, width=120) + "\nVIAS = " + pprint.pformat(vias, width=120) + "\n")
print("tracks", len(tracks), "vias", len(vias), "failed", failed)
